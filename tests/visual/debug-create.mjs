await Promise.all([p.waitForNavigation(),p.click('button[type="submit"]')]);
await p.goto(B+'/shipments/create');
console.log('cargo options:',await p.locator('select[name="cargo_type"] option').allTextContents());
console.log('unit options:',await p.locator('select[name="unit"] option').allTextContents());

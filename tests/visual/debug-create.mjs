import { chromium } from 'playwright-core';
const browser=await chromium.launch({executablePath:'C:/Program Files (x86)/Google/Chrome/Application/chrome.exe',headless:true,args:['--no-sandbox']});
const p=await (await browser.newContext()).newPage();
const B='http://localhost/cargo-management/public';
await p.goto(B+'/login');
await p.fill('input[name="email"]','admin@sl.com');
